import assert from 'node:assert/strict';
import { Client } from './auth.mjs';
const path='/api/ois/commands/';
const guest=new Client();
assert.equal((await guest.request('/api/ois/workspace')).status,401);
const [scheduler,clinician,physicist,admin]=await Promise.all(['scheduler','clinician','physicist','admin'].map(u=>new Client().login(u)));
assert.equal((await admin.request('/api/ois/workspace')).status,403);
assert.equal((await scheduler.request(path+'case',{patientId:1,text:'forbidden'},crypto.randomUUID())).status,403);
assert.equal((await clinician.request(path+'case',{patientId:1,text:'missing-key'})).status,400);
async function send(client,op,command,key=crypto.randomUUID()){const r=await client.request(path+op,command,key);assert.equal(r.status,200,JSON.stringify(r.body));return r.body.targetId;}
const caseId=await send(clinician,'case',{patientId:1,text:'HTTP OIS '+Date.now()});
await send(clinician,'prescribe',{id:caseId,version:1,diagnosis:'模拟诊断',text:'模拟处方'});
const planId=await send(physicist,'plan',{caseId,version:2,resourceId:'linac-a',text:'模拟计划'});
await send(clinician,'review',{id:planId,version:1});
assert.equal((await clinician.request(path+'validate',{id:'forged',version:1,outcome:'Passed',text:'禁止代签'},crypto.randomUUID())).status,403);
const base=new Date(Date.UTC(2036,0,1)+Math.floor(Math.random()*300)*86400000);
const booking={kind:'Treatment',patientId:1,caseId,resourceId:'linac-a',startUtc:base.toISOString(),endUtc:new Date(+base+1800000).toISOString()};
const key=crypto.randomUUID();const id=await send(scheduler,'book',booking,key);
assert.equal(await send(scheduler,'book',booking,key),id);
assert.equal((await scheduler.request(path+'book',booking,crypto.randomUUID())).status,409);
await send(scheduler,'cancel',{id,version:1,reason:'测试取消'});
await send(scheduler,'restore',{id,version:2,reason:'测试恢复'});
const state=(await scheduler.request('/api/ois/workspace')).body;
assert.equal(state.reservations.find(x=>x.reservation.id===id).reservation.status,'Booked');
assert.ok(state.reservations.find(x=>x.reservation.id===id).blockers.includes('待物理验证'));
assert.equal(state.plans.find(p=>p.id===planId).reviewedBy,'clinician');
assert.equal((await scheduler.request(path+'cancel',{id,version:1,reason:'过期版本'},crypto.randomUUID())).body.code,'version_conflict');
scheduler.token='';assert.equal((await scheduler.request(path+'cancel',{id,version:3,reason:'无CSRF'},crypto.randomUUID())).status,400);
if(process.env.Legacy__Enabled!=='true')assert.equal((await clinician.request('/api/agent/config')).status,404);
console.log('PASS OIS HTTP: roles, CSRF, plan registration/review, release blockers, conflicts, cancel/restore, versions and idempotency');
